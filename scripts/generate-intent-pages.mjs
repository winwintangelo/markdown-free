#!/usr/bin/env node
// Generates the route stubs for the long-tail intent pages (build plan Phase 1).
//
//   node scripts/generate-intent-pages.mjs          # write/refresh stubs, list URLs
//   node scripts/generate-intent-pages.mjs --check  # exit 1 if any stub is missing or stale
//
// Source of truth: src/content/intent-pages/manifest.json (+ the per-locale
// prose files). English pages live at the URL root (src/app/(en)/<slug>/),
// other locales under src/app/[locale]/<slug>/ — the same shapes as the
// hand-written intent pages, so no dynamic catch-all segment is needed.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = path.join(root, "src/content/intent-pages/manifest.json");
const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
const check = process.argv.includes("--check");

const HEADER = `// GENERATED by scripts/generate-intent-pages.mjs from src/content/intent-pages/manifest.json.
// Do not edit: change the manifest / locale content and re-run the generator.`;

function enStub(slug) {
  return `${HEADER}
import type { Metadata } from "next";
import { IntentPage, intentMetadata } from "@/components/intent-page";

const LOCALE = "en" as const;
const SLUG = ${JSON.stringify(slug)};

export const metadata: Metadata = intentMetadata(LOCALE, SLUG);

export default function Page() {
  return <IntentPage locale={LOCALE} slug={SLUG} />;
}
`;
}

/**
 * One stub per SLUG under src/app/[locale]/, listing every locale that
 * publishes that slug — several locales can share one (e.g. a brand name like
 * "claude-artifacts-pdf"), and they would otherwise overwrite each other's file.
 */
function localeStub(slug, locales) {
  return `${HEADER}
import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { IntentPage, intentMetadata } from "@/components/intent-page";
import { isValidLocale } from "@/i18n";

const SLUG = ${JSON.stringify(slug)};
const LOCALES = ${JSON.stringify(locales)} as const;

// This page exists only for the locales that publish this slug
export function generateStaticParams() {
  return LOCALES.map((locale) => ({ locale }));
}

function resolve(locale: string) {
  if (!isValidLocale(locale) || !(LOCALES as readonly string[]).includes(locale)) notFound();
  return locale as (typeof LOCALES)[number];
}

export async function generateMetadata({ params }: { params: Promise<{ locale: string }> }): Promise<Metadata> {
  const { locale } = await params;
  return intentMetadata(resolve(locale), SLUG);
}

export default async function Page({ params }: { params: Promise<{ locale: string }> }) {
  const { locale } = await params;
  return <IntentPage locale={resolve(locale)} slug={SLUG} />;
}
`;
}

// One route file per (surface, slug): EN pages live at the URL root, every
// other locale under [locale]/<slug> — grouped, because locales can share a slug.
const routes = new Map();
const urls = [];
for (const page of manifest.pages) {
  const key = page.locale === "en" ? `en:${page.slug}` : `locale:${page.slug}`;
  if (!routes.has(key)) routes.set(key, { en: page.locale === "en", slug: page.slug, locales: [] });
  if (page.locale !== "en") routes.get(key).locales.push(page.locale);
  urls.push(page.locale === "en" ? `/${page.slug}` : `/${page.locale}/${page.slug}`);
}

let written = 0;
let stale = 0;
for (const route of routes.values()) {
  const dir = route.en
    ? path.join(root, "src/app/(en)", route.slug)
    : path.join(root, "src/app/[locale]", route.slug);
  const file = path.join(dir, "page.tsx");
  const expected = route.en ? enStub(route.slug) : localeStub(route.slug, route.locales);
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (current === expected) continue;
  if (current !== null && !current.startsWith("// GENERATED by scripts/generate-intent-pages.mjs")) {
    console.error(`refusing to overwrite hand-written page: ${path.relative(root, file)}`);
    process.exit(1);
  }
  stale++;
  if (check) continue;
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(file, expected);
  written++;
}

if (check) {
  if (stale > 0) {
    console.error(`${stale} intent page stub(s) missing or stale — run: node scripts/generate-intent-pages.mjs`);
    process.exit(1);
  }
  console.log(`intent pages: ${manifest.pages.length} pages / ${routes.size} route files up to date`);
} else {
  console.log(
    `intent pages: ${manifest.pages.length} in manifest, ${routes.size} route file(s), ${written} written`
  );
  console.log(urls.join("\n"));
}
